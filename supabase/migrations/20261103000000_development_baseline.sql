-- JurisAI development baseline schema.
-- Creates the legacy-compatible empty domain tables required by migrations 001-004.
-- No production data is copied. This migration is intended for a fresh dev project.

begin;

create schema if not exists extensions;
create extension if not exists vector with schema extensions;

create table if not exists public.tenentes (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public."case" (
  id uuid primary key default gen_random_uuid(),
  tenente_id uuid references public.tenentes(id),
  title text not null,
  description text,
  created_at timestamptz not null default now()
);

-- Preserve the unexplained uppercase legacy table as a separate closed table.
create table if not exists public."CASE" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Name" text
);
alter table public."CASE" enable row level security;

create table if not exists public.document (
  id uuid primary key default gen_random_uuid(),
  case_id uuid references public."case"(id),
  file_name text not null,
  file_path text,
  created_at timestamptz not null default now()
);

create table if not exists public.embedding (
  id uuid primary key default gen_random_uuid(),
  document_id uuid references public.document(id),
  content text not null,
  vector extensions.vector(3),
  created_at timestamptz not null default now()
);

commit;
